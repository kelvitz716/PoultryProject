/**
 * @file db.js
 * @description SQLite database connection, WAL initialization, schema setup,
 * and database execution helper wrappers for the Poultry Decision Support System (PoultryDSS).
 * All schema changes, entity definitions, and database structures are maintained here.
 */

const sqlite3 = require('sqlite3').verbose();
const path = require('path');
const fs = require('fs');

// Ensure that the 'data' directory exists inside the project root directory
const dataDir = path.join(__dirname, 'data');
if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
}

// Establish connection to the persistent SQLite database
const dbPath = path.join(dataDir, 'poultry.db');
const db = new sqlite3.Database(dbPath, (err) => {
    if (err) {
        console.error('Error opening database:', err.message);
    } else {
        console.log('Connected to SQLite database.');
        // Configure Write-Ahead Logging (WAL) mode to allow concurrent reads and atomic commits
        db.run('PRAGMA journal_mode=WAL;', () => {
            initializeDatabase();
        });
    }
});

/**
 * Initializes the database tables and schemas if they do not already exist.
 * Executes sequentially inside db.serialize to avoid race conditions during creation.
 */
function initializeDatabase() {
    db.serialize(() => {
        // Core configuration, settings, and aggregate key-value store
        db.run(`
            CREATE TABLE IF NOT EXISTS entities (
                key TEXT PRIMARY KEY,
                value TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);
        
        // Economic models and project proposals generated by the system
        db.run(`
            CREATE TABLE IF NOT EXISTS proposals (
                id TEXT PRIMARY KEY,
                data TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Active flock cohort trackers and their progress states
        db.run(`
            CREATE TABLE IF NOT EXISTS batches (
                id TEXT PRIMARY KEY,
                data TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Finished historical cohort metrics used by the learning engine to refine models
        db.run(`
            CREATE TABLE IF NOT EXISTS snapshots (
                id TEXT PRIMARY KEY,
                data TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Daily records (mortality, feed logs, water consumption, lay counts) for all cohorts
        db.run(`
            CREATE TABLE IF NOT EXISTS logs (
                id TEXT PRIMARY KEY,
                batch_id TEXT NOT NULL,
                data TEXT NOT NULL,
                date TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Financial ledger (OPEX, CAPEX, revenue transactions) per batch
        db.run(`
            CREATE TABLE IF NOT EXISTS transactions (
                id TEXT PRIMARY KEY,
                batch_id TEXT NOT NULL,
                data TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Health event trackers (immunizations, medicine withdrawal logs)
        db.run(`
            CREATE TABLE IF NOT EXISTS health_logs (
                id TEXT PRIMARY KEY,
                batch_id TEXT NOT NULL,
                data TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);
        console.log('Database schema initialized.');
    });
}

/**
 * Executes a write query (INSERT, UPDATE, DELETE) and returns a Promise.
 * @param {string} sql - The SQL statement to run.
 * @param {Array<*>} [params=[]] - Binding parameters for the statement.
 * @returns {Promise<Object>} Resolves with the execution context (including `lastID` and `changes`).
 */
function runQuery(sql, params = []) {
    return new Promise((resolve, reject) => {
        db.run(sql, params, function (err) {
            if (err) reject(err);
            else resolve(this);
        });
    });
}

/**
 * Retrieves all matching rows from a query and returns a Promise.
 * @param {string} sql - The SQL query to run.
 * @param {Array<*>} [params=[]] - Binding parameters for the query.
 * @returns {Promise<Array<Object>>} Resolves with an array of matching rows.
 */
function allQuery(sql, params = []) {
    return new Promise((resolve, reject) => {
        db.all(sql, params, (err, rows) => {
            if (err) reject(err);
            else resolve(rows);
        });
    });
}

/**
 * Retrieves the first matching row from a query and returns a Promise.
 * @param {string} sql - The SQL query to run.
 * @param {Array<*>} [params=[]] - Binding parameters for the query.
 * @returns {Promise<Object|undefined>} Resolves with the first matching row object, or undefined.
 */
function getQuery(sql, params = []) {
    return new Promise((resolve, reject) => {
        db.get(sql, params, (err, row) => {
            if (err) reject(err);
            else resolve(row);
        });
    });
}

module.exports = {
    db,
    runQuery,
    allQuery,
    getQuery
};
