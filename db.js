/**
 * @file db.js
 * @description SQLite database connection, WAL initialization, schema setup,
 * and database execution helper wrappers for the Poultry Decision Support System (PoultryDSS).
 * All schema changes, entity definitions, and database structures are maintained here.
 */

const sqlite3 = require('sqlite3').verbose();
const path = require('path');
const fs = require('fs');

// Ensure that the 'data' directory exists inside the project root directory
const dataDir = path.join(__dirname, 'data');
if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
}

// Establish connection to the persistent SQLite database
const dbPath = path.join(dataDir, 'poultry.db');

/**
 * Module-level db reference. Set synchronously when the connection opens.
 * Helper functions (runQuery, allQuery, getQuery) reference this variable.
 * @type {sqlite3.Database|null}
 */
let db = null;

/**
 * Resolves when the DB connection is open and all schema tables have been created.
 * Awaited by server.js before the server begins listening or running recovery.
 * @type {Promise<void>}
 */
const dbReady = new Promise((resolve, reject) => {
    db = new sqlite3.Database(dbPath, (err) => {
        if (err) {
            console.error('Error opening database:', err.message);
            reject(err);
        } else {
            console.log('Connected to SQLite database.');
            db.run('PRAGMA journal_mode=WAL;', () => {
                db.run('PRAGMA foreign_keys=ON;', () => {
                    db.run('PRAGMA busy_timeout=5000;', () => {
                        initializeDatabase(db, resolve, reject);
                    });
                });
            });
        }
    });
});

/**
 * Checks if a column exists in a table, and if not, adds it.
 * @param {sqlite3.Database} db - SQLite database instance.
 * @param {string} table - Table name.
 * @param {string} column - Column name.
 * @param {string} columnDef - SQLite column definition type.
 * @returns {Promise<void>}
 */
function migrateTableColumn(db, table, column, columnDef) {
    return new Promise((resolve, reject) => {
        db.get(`SELECT COUNT(*) as count FROM pragma_table_info('${table}') WHERE name='${column}'`, (err, row) => {
            if (err) {
                return reject(err);
            }
            if (!row || row.count === 0) {
                db.run(`ALTER TABLE ${table} ADD COLUMN ${column} ${columnDef}`, (alterErr) => {
                    if (alterErr) {
                        reject(alterErr);
                    } else {
                        console.log(`Migration: added ${column} column to ${table} table.`);
                        resolve();
                    }
                });
            } else {
                resolve();
            }
        });
    });
}

/**
 * Initializes the database tables and schemas if they do not already exist.
 * Executes sequentially inside db.serialize to avoid race conditions during creation.
 * @param {sqlite3.Database} db - Open database instance.
 * @param {Function} resolve - Promise resolve callback (called after all tables created).
 * @param {Function} reject - Promise reject callback.
 */
function initializeDatabase(db, resolve, reject) {
    db.serialize(() => {
        // Core configuration, settings, and aggregate key-value store
        db.run(`
            CREATE TABLE IF NOT EXISTS entities (
                key TEXT PRIMARY KEY,
                value TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);
        
        // Economic models and project proposals generated by the system
        db.run(`
            CREATE TABLE IF NOT EXISTS proposals (
                id TEXT PRIMARY KEY,
                data TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Active flock cohort trackers and their progress states
        db.run(`
            CREATE TABLE IF NOT EXISTS batches (
                id TEXT PRIMARY KEY,
                data TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Finished historical cohort metrics used by the learning engine to refine models
        db.run(`
            CREATE TABLE IF NOT EXISTS snapshots (
                id TEXT PRIMARY KEY,
                data TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Daily records (mortality, feed logs, water consumption, lay counts) for all cohorts
        db.run(`
            CREATE TABLE IF NOT EXISTS logs (
                id TEXT PRIMARY KEY,
                batch_id TEXT NOT NULL,
                data TEXT NOT NULL,
                date TEXT NOT NULL,
                logged_by TEXT,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Financial ledger (OPEX, CAPEX, revenue transactions) per batch
        db.run(`
            CREATE TABLE IF NOT EXISTS transactions (
                id TEXT PRIMARY KEY,
                batch_id TEXT NOT NULL,
                data TEXT NOT NULL,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Health event trackers (immunizations, medicine withdrawal logs)
        db.run(`
            CREATE TABLE IF NOT EXISTS health_logs (
                id TEXT PRIMARY KEY,
                batch_id TEXT NOT NULL,
                data TEXT NOT NULL,
                logged_by TEXT,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // ── STAGING LAYER ────────────────────────────────────────────────────────
        // Persistent intra-day event buffer. All operational writes land here first.
        // A midnight commit job aggregates and finalises records into the permanent
        // tables (logs, health_logs, transactions). Rows are never deleted — they
        // form an immutable audit trail. status: 'pending'|'committed'|'orphaned'|'amendment'
        db.run(`
            CREATE TABLE IF NOT EXISTS staging (
                id          TEXT PRIMARY KEY,
                batch_id    TEXT NOT NULL,
                module      TEXT NOT NULL,
                date        TEXT NOT NULL,
                timestamp   TEXT NOT NULL,
                data        TEXT NOT NULL,
                status      TEXT NOT NULL DEFAULT 'pending',
                sensor_id   TEXT NOT NULL DEFAULT 'primary',
                logged_by   TEXT,
                created_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
                updated_at  DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);
        db.run(`
            CREATE INDEX IF NOT EXISTS idx_staging_batch_date
            ON staging (batch_id, date, status)
        `);
        db.run(`
            CREATE INDEX IF NOT EXISTS idx_staging_module_date
            ON staging (module, date, status)
        `);

        // ── AUTH ─────────────────────────────────────────────────────────────────
        // User accounts and role-based access control.
        // roles: 'super_admin' | 'admin' | 'farmer' | 'viewer'
        db.run(`
            CREATE TABLE IF NOT EXISTS users (
                id            TEXT PRIMARY KEY,
                username      TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                role          TEXT NOT NULL DEFAULT 'viewer',
                created_by    TEXT,
                must_change_password INTEGER NOT NULL DEFAULT 0,
                is_active     INTEGER NOT NULL DEFAULT 1,
                created_at    DATETIME DEFAULT CURRENT_TIMESTAMP,
                updated_at    DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // ── DOUBLE-ENTRY GENERAL LEDGER ──────────────────────────────────────────
        db.run(`
            CREATE TABLE IF NOT EXISTS ledger_accounts (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                type TEXT CHECK(type IN ('asset', 'liability', 'equity', 'revenue', 'expense')),
                code TEXT UNIQUE NOT NULL
            )
        `);

        db.run(`
            CREATE TABLE IF NOT EXISTS ledger_transactions (
                id TEXT PRIMARY KEY,
                date TEXT NOT NULL,
                description TEXT,
                ref_type TEXT,
                ref_id TEXT
            )
        `);

        db.run(`
            CREATE TABLE IF NOT EXISTS ledger_entries (
                id TEXT PRIMARY KEY,
                transaction_id TEXT REFERENCES ledger_transactions(id) ON DELETE CASCADE,
                account_id TEXT REFERENCES ledger_accounts(id),
                entry_type TEXT CHECK(entry_type IN ('debit', 'credit')),
                amount REAL NOT NULL CHECK(amount > 0)
            )
        `);

        // Seed default chart of accounts
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('1000', 'Liquid Cash Box', 'asset', '1000')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('1010', 'M-Pesa Till', 'asset', '1010')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('1200', 'Accounts Receivable (CRM)', 'asset', '1200')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('1300', 'Egg Inventory', 'asset', '1300')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('1310', 'Feed Inventory', 'asset', '1310')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('4000', 'Egg Sales Revenue', 'revenue', '4000')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('4010', 'Flock Sales Revenue', 'revenue', '4010')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('5000', 'Feed Expense', 'expense', '5000')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('5010', 'Labor Expense', 'expense', '5010')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('5020', 'Utilities Expense', 'expense', '5020')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('5030', 'Medication Expense', 'expense', '5030')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('5040', 'Chicks Expense', 'expense', '5040')");
        db.run("INSERT OR IGNORE INTO ledger_accounts (id, name, type, code) VALUES ('9999', 'Suspense Account', 'asset', '9999')");

        // Add a unique index to handle existing/new databases and enforce ref_id uniqueness
        db.run(`
            CREATE UNIQUE INDEX IF NOT EXISTS idx_ledger_ref_type_id
            ON ledger_transactions (ref_type, ref_id)
        `);

        // Migration: Add is_active column to users table if missing (SQLite ALTER COLUMN support guard)
        db.all("PRAGMA table_info(users)", (err, columns) => {
            if (err) {
                reject(err);
                return;
            }
            const hasIsActive = columns && columns.some(col => col.name === 'is_active');
            
            const runNextMigrations = () => {
                migrateTableColumn(db, 'staging', 'logged_by', 'TEXT')
                    .then(() => migrateTableColumn(db, 'health_logs', 'logged_by', 'TEXT'))
                    .then(() => migrateTableColumn(db, 'logs', 'logged_by', 'TEXT'))
                    .then(() => {
                        console.log('Database schema initialized.');
                        resolve();
                    })
                    .catch((migErr) => {
                        reject(migErr);
                    });
            };

            if (!hasIsActive) {
                db.run("ALTER TABLE users ADD COLUMN is_active INTEGER NOT NULL DEFAULT 1", (alterErr) => {
                    if (alterErr) {
                        reject(alterErr);
                    } else {
                        console.log('Migration: added is_active column to users table.');
                        runNextMigrations();
                    }
                });
            } else {
                runNextMigrations();
            }
        });
    });
}

/**
 * Executes a write query (INSERT, UPDATE, DELETE) and returns a Promise.
 * @param {string} sql - The SQL statement to run.
 * @param {Array<*>} [params=[]] - Binding parameters for the statement.
 * @returns {Promise<Object>} Resolves with the execution context (including `lastID` and `changes`).
 */
function runQuery(sql, params = []) {
    return new Promise((resolve, reject) => {
        db.run(sql, params, function (err) {
            if (err) reject(err);
            else resolve(this);
        });
    });
}

/**
 * Retrieves all matching rows from a query and returns a Promise.
 * @param {string} sql - The SQL query to run.
 * @param {Array<*>} [params=[]] - Binding parameters for the query.
 * @returns {Promise<Array<Object>>} Resolves with an array of matching rows.
 */
function allQuery(sql, params = []) {
    return new Promise((resolve, reject) => {
        db.all(sql, params, (err, rows) => {
            if (err) reject(err);
            else resolve(rows);
        });
    });
}

/**
 * Retrieves the first matching row from a query and returns a Promise.
 * @param {string} sql - The SQL query to run.
 * @param {Array<*>} [params=[]] - Binding parameters for the query.
 * @returns {Promise<Object|undefined>} Resolves with the first matching row object, or undefined.
 */
function getQuery(sql, params = []) {
    return new Promise((resolve, reject) => {
        db.get(sql, params, (err, row) => {
            if (err) reject(err);
            else resolve(row);
        });
    });
}

module.exports = {
    dbReady,
    runQuery,
    allQuery,
    getQuery
};

// Export db as a live getter so callers always get the current value
// (db is assigned synchronously when new sqlite3.Database() is called)
Object.defineProperty(module.exports, 'db', { get: () => db, enumerable: true });

